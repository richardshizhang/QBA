#!/usr/bin/env python3
"""Build faculty collaboration edges from the downloaded papers.

Two faculty members are linked when both are kept authors of the same paper in
data/papers/papers.json (after the filters and hand overrides in fetch_papers.py).

Each shared paper adds 1/(n - 1) to the pair's strength, where n is the paper's
author count (Newman's collaboration weight, Phys. Rev. E 64, 016132, 2001). A
two-author paper adds 1, a ten-author paper 0.11, and a 100-author consortium paper
about 0.01, so a handful of consortium papers can't outweigh real working
relationships. Author counts are capped at 100 in the downloaded records, which only
makes the very largest papers count slightly more than they should.

Writes data/edges.json (used by the map) and data/collaboration-report.md.

    python3 scripts/build_edges.py

Only the standard library is used.
"""

import collections
import itertools
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACULTY = os.path.join(ROOT, "data", "faculty.json")
PAPERS = os.path.join(ROOT, "data", "papers", "papers.json")
EDGES = os.path.join(ROOT, "data", "edges.json")
REPORT = os.path.join(ROOT, "data", "collaboration-report.md")

GROUPS = ("core", "joint", "emeritus")
SIZE_BINS = [("2-10", 10), ("11-50", 50), ("51+", float("inf"))]
EXAMPLES = 8  # papers listed per edge in edges.json


def size_bin(n):
    return next(label for label, top in SIZE_BINS if n <= top)


def paper_weight(n_authors):
    return 1 / (max(n_authors, 2) - 1)


def main():
    with open(FACULTY, encoding="utf-8") as f:
        faculty = [p for p in json.load(f)["faculty"] if p["group"] in GROUPS]
    with open(PAPERS, encoding="utf-8") as f:
        works = json.load(f)["works"]
    names = {p["id"]: p["name"] for p in faculty}

    shared = collections.defaultdict(list)
    for w in works.values():
        if w["duplicate_of"]:
            continue
        people = sorted(pid for pid, info in w["faculty"].items() if info["keep"] and pid in names)
        for a, b in itertools.combinations(people, 2):
            shared[(a, b)].append(w)

    edges = []
    for (a, b), ws in shared.items():
        by_size = collections.Counter(size_bin(w["n_authors"]) for w in ws)
        years = [w["year"] for w in ws if w["year"]]
        # Small, recent papers say the most about what a pair works on together.
        examples = sorted(ws, key=lambda w: (w["n_authors"] > 50, -(w["year"] or 0), w["n_authors"]))
        edges.append({
            "source": a,
            "target": b,
            "strength": round(sum(paper_weight(w["n_authors"]) for w in ws), 3),
            "papers": len(ws),
            "by_size": {label: by_size[label] for label, _ in SIZE_BINS},
            "at_usc": sum(1 for w in ws if w["faculty"][a].get("usc") and w["faculty"][b].get("usc")),
            "first_year": min(years) if years else None,
            "last_year": max(years) if years else None,
            "examples": [{"id": w["id"], "title": w["title"], "year": w["year"],
                          "authors": w["n_authors"], "venue": w["venue"]} for w in examples[:EXAMPLES]],
        })
    edges.sort(key=lambda e: (-e["strength"], e["source"], e["target"]))

    summary = {p["id"]: {"collaborators": 0, "strength": 0.0} for p in faculty}
    for e in edges:
        for pid in (e["source"], e["target"]):
            summary[pid]["collaborators"] += 1
            summary[pid]["strength"] = round(summary[pid]["strength"] + e["strength"], 3)

    out = {
        "weighting": "each shared paper adds 1/(authors - 1) to a pair's strength (Newman 2001)",
        "size_bins": [label for label, _ in SIZE_BINS],
        "edges": edges,
        "faculty": summary,
    }
    with open(EDGES, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")
    write_report(edges, summary, faculty, names)
    linked = sum(1 for s in summary.values() if s["collaborators"])
    print(f"wrote {len(edges)} edges among {linked} of {len(faculty)} faculty to "
          f"{os.path.relpath(EDGES, ROOT)}; report in {os.path.relpath(REPORT, ROOT)}")


def write_report(edges, summary, faculty, names):
    lines = [
        "# Collaboration report",
        "",
        "Generated by `scripts/build_edges.py` from the papers kept by `scripts/fetch_papers.py`.",
        "**Strength** adds 1/(authors − 1) per shared paper, so a two-author paper counts 1 and a",
        "100-author consortium paper about 0.01. **At USC** counts shared papers on which both",
        "list a USC affiliation.",
        "",
        "| Pair | Strength | Papers | 2–10 authors | 11–50 | 51+ | At USC | Years | Example |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for e in edges:
        ex = e["examples"][0]
        title = ex["title"] if len(ex["title"]) <= 70 else ex["title"][:67] + "..."
        years = (f"{e['first_year']}–{e['last_year']}" if e["first_year"] != e["last_year"]
                 else str(e["first_year"]))
        s = e["by_size"]
        lines.append(
            f"| {names[e['source']]} — {names[e['target']]} | **{e['strength']:.2f}** | {e['papers']} | "
            f"{s['2-10'] or ''} | {s['11-50'] or ''} | {s['51+'] or ''} | {e['at_usc'] or ''} | {years} | "
            f"[{title.replace('|', '/')}](https://openalex.org/{ex['id']}) ({ex['year']}) |")

    ranked = sorted((p for p in faculty if summary[p["id"]]["collaborators"]),
                    key=lambda p: (-summary[p["id"]]["collaborators"], -summary[p["id"]]["strength"]))
    alone = [p["name"] for p in faculty if not summary[p["id"]]["collaborators"]]
    lines += ["", "## Most connected", "",
              "| Faculty | QCB co-authors | Total strength |", "|---|---|---|"]
    for p in ranked[:15]:
        s = summary[p["id"]]
        lines.append(f"| {p['name']} | {s['collaborators']} | {s['strength']:.2f} |")
    lines += ["", f"## No co-authored papers with other QCB faculty ({len(alone)})", "",
              ", ".join(alone) + ".", ""]
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
